    _desc = _INDICATOR_DESCRIPTIONS.get(_field, "")
    _meta["desc"] = _desc + _COUNTRY_DEGENERATE_NOTE if _degenerate else _desc
    # 契约字段:前端在国家级粒度隐藏被标记的字段,避免展示零信息的常数中心性。
    _meta["country_degenerate"] = _degenerate
